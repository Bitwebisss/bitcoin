/**
 * crypto_argon2_api_tests.cpp
 *
 * Tests for the ported Argon2 library against Python-generated test vectors.
 * Covers every public API surface:
 *
 *   argon2[d/i/id]_hash_raw       – typed convenience wrappers, all ISAs
 *   argon2[d/i/id]_hash_encoded   – typed wrappers, exact PHC-string match
 *   argon2[d/i/id]_verify         – typed verify against Python vectors
 *   argon2_hash()                 – generic wrapper, raw and encoded paths
 *   argon2_verify()               – generic verify
 *   argon2_ctx() / argon2[d/i/id]_ctx()        – low-level context API
 *   argon2[d/i/id]_verify_ctx() / argon2_verify_ctx() – context verify
 *   argon2_encodedlen()           – predicted size must match actual
 *   argon2_error_message()        – non-null/non-empty for all known codes
 *
 * Vectors are generated by generate_argon2_api_vectors.py (argon2-cffi).
 */

