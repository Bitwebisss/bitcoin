// Test 3 – _verify: Python-generated encoded strings must verify correctly
// ---------------------------------------------------------------------------
BOOST_AUTO_TEST_CASE(argon2_verify_vectors)
{
    UniValue root = LoadVectors();
    const UniValue& vecs = root["encoded_vectors"];
    BOOST_REQUIRE(vecs.isArray());
    BOOST_REQUIRE_GT(vecs.size(), 0);

    Argon2AutoDetect(argon2_implementation::STANDARD);
    size_t failures = 0;

    for (size_t i = 0; i < vecs.size(); ++i) {
        const UniValue& v       = vecs[i];
        const std::string ts    = v["type"].get_str();
        const auto data         = ParseHex(v["data"].get_str());
        const std::string enc   = v["encoded"].get_str();
        const argon2_type type  = ParseArgon2Type(ts);

        // Correct data → must verify
        int rc = TypedVerify(type, enc.c_str(), data.data(), data.size());
        if (rc != ARGON2_OK) {
            ++failures;
            BOOST_TEST_MESSAGE("VERIFY FAIL vec=" << i << " type=" << ts
                << " rc=" << rc << " encoded=" << enc);
        }

        // Corrupted data → must not verify
        std::vector<uint8_t> corrupt = data;
        corrupt[0] ^= 0xFF;
        BOOST_CHECK_NE(TypedVerify(type, enc.c_str(), corrupt.data(), corrupt.size()),
                       ARGON2_OK);
    }

    Argon2AutoDetect();
    BOOST_REQUIRE_EQUAL(failures, 0);
}

