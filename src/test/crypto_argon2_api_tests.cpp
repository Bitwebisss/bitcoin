/**
 * crypto_argon2_api_tests.cpp
 *
 * Full-coverage tests for the ported Argon2 library (all three variants:
 * argon2d, argon2i, argon2id) and every public API surface:
 *
 *   _hash_raw         – all three type-specific convenience wrappers
 *   _hash_encoded     – all three type-specific wrappers
 *   _verify           – all three type-specific wrappers
 *   argon2_hash()     – generic function, raw-only and encoded-only paths
 *   argon2_verify()   – generic verify
 *   argon2_ctx()      – low-level context API, generic
 *   argon2[d/i/id]_ctx()         – type-specific context wrappers
 *   argon2[d/i/id]_verify_ctx()  – type-specific context verify
 *   argon2_encodedlen()           – utility: returned size must match actual
 *   argon2_error_message()        – non-null/non-empty for all known codes
 *
 * ISA variants (STANDARD, SSE2, SSSE3, AVX2, AVX512, NEON where compiled in)
 * are exercised by all tests that involve raw hash computation.
 *
 * This is a pure library test — it is NOT a consensus test.
 * Vectors are generated by generate_argon2_api_vectors.py using the
 * reference argon2-cffi Python bindings (libargon2).
 */

