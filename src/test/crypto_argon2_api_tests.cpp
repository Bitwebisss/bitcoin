// Test 9 – argon2_encodedlen(): returned size must equal strlen(enc) + 1
// ---------------------------------------------------------------------------
BOOST_AUTO_TEST_CASE(argon2_encodedlen_utility)
{
    struct Case {
        argon2_type type;
        uint32_t t, m, p, saltlen, hashlen;
    };
    const Case cases[] = {
        {Argon2_d,  1,  64, 1,  8, 16},
        {Argon2_i,  2, 128, 1,  8, 32},
        {Argon2_id, 3, 256, 1, 16, 32},
        {Argon2_id, 1,  64, 4, 32, 32},
        {Argon2_i,  1,  64, 1, 64, 64},
        {Argon2_d,  1, 128, 2, 16, 32},
        {Argon2_id, 1,  64, 1,  8, 64},
    };

    const std::vector<uint8_t> pwd(16, 0xAB);

    Argon2AutoDetect(argon2_implementation::STANDARD);

    for (const auto& c : cases) {
        const std::vector<uint8_t> salt(c.saltlen, 0xCD);
        size_t enc_len = argon2_encodedlen(c.t, c.m, c.p,
                                            c.saltlen, c.hashlen, c.type);
        BOOST_REQUIRE_GT(enc_len, 0);

        std::vector<char> buf(enc_len);
        int rc = TypedHashEncoded(c.type, c.t, c.m, c.p,
                                   pwd.data(), pwd.size(),
                                   salt.data(), salt.size(),
                                   c.hashlen, buf.data(), enc_len);
        BOOST_REQUIRE_MESSAGE(rc == ARGON2_OK,
            "hash_encoded rc=" << rc << " for encodedlen case type=" << (int)c.type);

        // argon2_encodedlen must predict the exact buffer requirement
        // (string length + null terminator)
        size_t actual = std::strlen(buf.data()) + 1;
        BOOST_CHECK_MESSAGE(actual == enc_len,
            "encodedlen mismatch: predicted=" << enc_len
            << " actual=" << actual
            << " type=" << (int)c.type);
    }

    Argon2AutoDetect();
}

