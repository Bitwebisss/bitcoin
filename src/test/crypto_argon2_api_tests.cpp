/** Map the JSON "type" string to the argon2_type enum. */
static argon2_type ParseArgon2Type(const std::string& s)
{
    if (s == "argon2d")  return Argon2_d;
    if (s == "argon2i")  return Argon2_i;
    if (s == "argon2id") return Argon2_id;
    BOOST_FAIL("Unknown argon2 type string: " + s);
    return Argon2_id; // unreachable
}

/** Dispatch to the correct typed _hash_raw wrapper. */
static int TypedHashRaw(argon2_type type,
                         uint32_t t, uint32_t m, uint32_t p,
                         const void* pwd, size_t pwdlen,
                         const void* salt, size_t saltlen,
                         void* hash, size_t hashlen)
{
    switch (type) {
    case Argon2_d:  return argon2d_hash_raw(t, m, p, pwd, pwdlen, salt, saltlen, hash, hashlen);
    case Argon2_i:  return argon2i_hash_raw(t, m, p, pwd, pwdlen, salt, saltlen, hash, hashlen);
    case Argon2_id: return argon2id_hash_raw(t, m, p, pwd, pwdlen, salt, saltlen, hash, hashlen);
    }
    return ARGON2_INCORRECT_TYPE;
}

/** Dispatch to the correct typed _hash_encoded wrapper. */
static int TypedHashEncoded(argon2_type type,
                             uint32_t t, uint32_t m, uint32_t p,
                             const void* pwd, size_t pwdlen,
                             const void* salt, size_t saltlen,
                             size_t hashlen, char* enc, size_t enclen)
{
    switch (type) {
    case Argon2_d:  return argon2d_hash_encoded(t, m, p, pwd, pwdlen, salt, saltlen, hashlen, enc, enclen);
    case Argon2_i:  return argon2i_hash_encoded(t, m, p, pwd, pwdlen, salt, saltlen, hashlen, enc, enclen);
    case Argon2_id: return argon2id_hash_encoded(t, m, p, pwd, pwdlen, salt, saltlen, hashlen, enc, enclen);
    }
    return ARGON2_INCORRECT_TYPE;
}

/** Dispatch to the correct typed _verify wrapper. */
static int TypedVerify(argon2_type type,
                        const char* encoded,
                        const void* pwd, size_t pwdlen)
{
    switch (type) {
    case Argon2_d:  return argon2d_verify(encoded, pwd, pwdlen);
    case Argon2_i:  return argon2i_verify(encoded, pwd, pwdlen);
    case Argon2_id: return argon2id_verify(encoded, pwd, pwdlen);
    }
    return ARGON2_INCORRECT_TYPE;
}

/** Expected PHC-string prefix for a given type. */
static std::string TypePrefix(argon2_type type)
{
    switch (type) {
    case Argon2_d:  return "$argon2d$";
    case Argon2_i:  return "$argon2i$";
    case Argon2_id: return "$argon2id$";
    }
    return "";
}

/**
 * Invoke `fn` once for each ISA variant that was compiled into this binary.
 * STANDARD is always included; SIMD variants are gated by their compile-time
 * defines (same macros forwarded from the library CMakeLists).
 */
static void ForEachISA(
    const std::function<void(argon2_implementation::UseImplementation,
                             const std::string&)>& fn)
{
    fn(argon2_implementation::STANDARD, "STANDARD");
#if defined(ENABLE_ARGON2_SSE2)
    fn(argon2_implementation::USE_SSE2,   "SSE2");
#endif
#if defined(ENABLE_ARGON2_SSSE3)
    fn(argon2_implementation::USE_SSSE3,  "SSSE3");
#endif
#if defined(ENABLE_ARGON2_AVX2)
    fn(argon2_implementation::USE_AVX2,   "AVX2");
#endif
#if defined(ENABLE_ARGON2_AVX512)
    fn(argon2_implementation::USE_AVX512, "AVX512");
#endif
#if defined(ENABLE_ARGON2_NEON)
    fn(argon2_implementation::USE_NEON,   "NEON");
#endif
}

// ---------------------------------------------------------------------------
// Test 1 – _hash_raw: all types × all ISAs against Python reference vectors
// ---------------------------------------------------------------------------
BOOST_AUTO_TEST_CASE(argon2_raw_all_types_all_isa)
{
    UniValue root = read_json(json_tests::argon2_api_test_vectors);
    const UniValue& vecs = root["raw_vectors"];
    BOOST_REQUIRE(vecs.isArray());
    BOOST_REQUIRE_GT(vecs.size(), 0);

    size_t failures = 0;

    for (size_t idx = 0; idx < vecs.size(); ++idx) {
        const UniValue& v        = vecs[idx];
        const std::string type_s = v["type"].get_str();
        const uint32_t t         = v["t_cost"].getInt<uint32_t>();
        const uint32_t m         = v["m_cost"].getInt<uint32_t>();
        const uint32_t p         = v["parallelism"].getInt<uint32_t>();
        const size_t hlen        = v["hash_len"].getInt<size_t>();
        const auto data          = ParseHex(v["data"].get_str());
        const auto salt          = ParseHex(v["salt"].get_str());
        const auto expected      = ParseHex(v["expected_hash"].get_str());
        const argon2_type type   = ParseArgon2Type(type_s);

        BOOST_REQUIRE(!data.empty());
        BOOST_REQUIRE(!salt.empty());
        BOOST_REQUIRE(expected.size() == hlen);

        ForEachISA([&](argon2_implementation::UseImplementation impl,
                       const std::string& isa_name) {
            Argon2AutoDetect(impl);
            std::vector<uint8_t> out(hlen);
            int rc = TypedHashRaw(type, t, m, p,
                                   data.data(), data.size(),
                                   salt.data(), salt.size(),
                                   out.data(), hlen);
            BOOST_REQUIRE_MESSAGE(rc == ARGON2_OK,
                isa_name << " hash_raw rc=" << rc
                         << " (vec=" << idx << " type=" << type_s << ")");
            if (out != expected) {
                ++failures;
                std::cerr
                    << "MISMATCH hash_raw vec=" << idx
                    << " type=" << type_s << " isa=" << isa_name
                    << " t=" << t << " m=" << m << " p=" << p
                    << " hlen=" << hlen << "\n"
                    << "  data:     " << v["data"].get_str() << "\n"
                    << "  salt:     " << v["salt"].get_str() << "\n"
                    << "  expected: " << v["expected_hash"].get_str() << "\n"
                    << "  actual:   " << HexStr(out) << "\n";
            }
        });
    }

    Argon2AutoDetect();
    BOOST_REQUIRE_EQUAL(failures, 0);
}

// ---------------------------------------------------------------------------
// Test 2 – _hash_encoded: format validation (prefix, v=19, m/t/p params)
// ---------------------------------------------------------------------------
BOOST_AUTO_TEST_CASE(argon2_encoded_format_check)
{
    UniValue root = read_json(json_tests::argon2_api_test_vectors);
    const UniValue& vecs = root["encoded_vectors"];
    BOOST_REQUIRE(vecs.isArray());
    BOOST_REQUIRE_GT(vecs.size(), 0);

    // Encoded output is deterministic given the inputs, ISA doesn't matter.
    Argon2AutoDetect(argon2_implementation::STANDARD);

    for (size_t idx = 0; idx < vecs.size(); ++idx) {
        const UniValue& v      = vecs[idx];
        const std::string ts   = v["type"].get_str();
        const uint32_t t       = v["t_cost"].getInt<uint32_t>();
        const uint32_t m       = v["m_cost"].getInt<uint32_t>();
        const uint32_t p       = v["parallelism"].getInt<uint32_t>();
        const size_t hlen      = v["hash_len"].getInt<size_t>();
        const auto data        = ParseHex(v["data"].get_str());
        const auto salt        = ParseHex(v["salt"].get_str());
        const argon2_type type = ParseArgon2Type(ts);

        // Let argon2_encodedlen determine the required buffer size
        size_t enc_len = argon2_encodedlen(t, m, p,
                                            static_cast<uint32_t>(salt.size()),
                                            static_cast<uint32_t>(hlen),
                                            type);
        BOOST_REQUIRE_GT(enc_len, 0);
        std::vector<char> enc_buf(enc_len);

        int rc = TypedHashEncoded(type, t, m, p,
                                   data.data(), data.size(),
                                   salt.data(), salt.size(),
                                   hlen, enc_buf.data(), enc_len);
        BOOST_REQUIRE_MESSAGE(rc == ARGON2_OK,
            "hash_encoded rc=" << rc << " vec=" << idx << " type=" << ts);

        const std::string enc(enc_buf.data());

        // 1. Must start with the correct type identifier
        const std::string prefix = TypePrefix(type);
        BOOST_CHECK_MESSAGE(enc.rfind(prefix, 0) == 0,
            "Wrong prefix at vec=" << idx << " type=" << ts
            << " got='" << enc.substr(0, prefix.size() + 2) << "'");

        // 2. Must embed the version
        BOOST_CHECK_MESSAGE(enc.find("v=19") != std::string::npos,
            "Missing 'v=19' at vec=" << idx);

        // 3. Must embed all three cost parameters
        BOOST_CHECK_MESSAGE(enc.find("m=" + std::to_string(m)) != std::string::npos,
            "Missing m_cost at vec=" << idx);
        BOOST_CHECK_MESSAGE(enc.find("t=" + std::to_string(t)) != std::string::npos,
            "Missing t_cost at vec=" << idx);
        BOOST_CHECK_MESSAGE(enc.find("p=" + std::to_string(p)) != std::string::npos,
            "Missing parallelism at vec=" << idx);

        // 4. Must match the Python-generated encoded string exactly
        const std::string py_enc = v["encoded"].get_str();
        BOOST_CHECK_MESSAGE(enc == py_enc,
            "Encoded mismatch vec=" << idx << " type=" << ts
            << "\n  cpp: " << enc
            << "\n  py:  " << py_enc);
    }

    Argon2AutoDetect();
}

