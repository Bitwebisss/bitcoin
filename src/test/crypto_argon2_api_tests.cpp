// ---------------------------------------------------------------------------
// Test 7 – argon2[d/i/id]_ctx() and argon2_ctx(): output must match _hash_raw
// ---------------------------------------------------------------------------
BOOST_AUTO_TEST_CASE(argon2_ctx_api)
{
    UniValue root = read_json(json_tests::argon2_api_test_vectors);
    const UniValue& vecs = root["raw_vectors"];
    BOOST_REQUIRE(vecs.isArray());
    BOOST_REQUIRE_GT(vecs.size(), 0);

    Argon2AutoDetect(argon2_implementation::STANDARD);
    size_t failures = 0;

    for (size_t idx = 0; idx < vecs.size(); ++idx) {
        const UniValue& v        = vecs[idx];
        const std::string ts     = v["type"].get_str();
        const uint32_t t         = v["t_cost"].getInt<uint32_t>();
        const uint32_t m         = v["m_cost"].getInt<uint32_t>();
        const uint32_t p         = v["parallelism"].getInt<uint32_t>();
        const size_t hlen        = v["hash_len"].getInt<size_t>();
        auto data                = ParseHex(v["data"].get_str());
        auto salt                = ParseHex(v["salt"].get_str());
        const auto expected      = ParseHex(v["expected_hash"].get_str());
        const argon2_type type   = ParseArgon2Type(ts);

        auto run_ctx = [&](bool generic) -> bool {
            std::vector<uint8_t> out(hlen, 0);
            argon2_context ctx;
            std::memset(&ctx, 0, sizeof(ctx));
            ctx.out          = out.data();
            ctx.outlen       = static_cast<uint32_t>(hlen);
            ctx.pwd          = data.data();
            ctx.pwdlen       = static_cast<uint32_t>(data.size());
            ctx.salt         = salt.data();
            ctx.saltlen      = static_cast<uint32_t>(salt.size());
            ctx.secret       = nullptr;
            ctx.secretlen    = 0;
            ctx.ad           = nullptr;
            ctx.adlen        = 0;
            ctx.t_cost       = t;
            ctx.m_cost       = m;
            ctx.lanes        = p;
            ctx.threads      = p;
            ctx.version      = ARGON2_VERSION_NUMBER;
            ctx.allocate_cbk = nullptr;
            ctx.free_cbk     = nullptr;
            ctx.flags        = ARGON2_DEFAULT_FLAGS;

            int rc;
            if (generic) {
                rc = argon2_ctx(&ctx, type);
            } else {
                switch (type) {
                case Argon2_d:  rc = argon2d_ctx(&ctx);  break;
                case Argon2_i:  rc = argon2i_ctx(&ctx);  break;
                case Argon2_id: rc = argon2id_ctx(&ctx); break;
                default:        rc = ARGON2_INCORRECT_TYPE;
                }
            }
            BOOST_REQUIRE_MESSAGE(rc == ARGON2_OK,
                (generic ? "argon2_ctx" : "argon2[d/i/id]_ctx")
                << " rc=" << rc << " vec=" << idx);
            return out == expected;
        };

        // Typed ctx
        if (!run_ctx(false)) {
            ++failures;
            std::cerr << "CTX MISMATCH (typed) vec=" << idx << " type=" << ts << "\n";
        }
        // Generic ctx
        if (!run_ctx(true)) {
            ++failures;
            std::cerr << "CTX MISMATCH (generic) vec=" << idx << " type=" << ts << "\n";
        }
    }

    Argon2AutoDetect();
    BOOST_REQUIRE_EQUAL(failures, 0);
}

// ---------------------------------------------------------------------------
// Test 8 – argon2[d/i/id]_verify_ctx(): verify the low-level verify path
// ---------------------------------------------------------------------------
BOOST_AUTO_TEST_CASE(argon2_verify_ctx_api)
{
    const uint8_t pwd[]     = "hunter2";
    const uint8_t salt[]    = "saltsalt";   // 8 bytes
    const size_t  pwdlen    = sizeof(pwd)  - 1;
    const size_t  saltlen   = sizeof(salt) - 1;
    constexpr size_t hlen   = 32;

    const argon2_type types[] = {Argon2_d, Argon2_i, Argon2_id};

    Argon2AutoDetect(argon2_implementation::STANDARD);

    for (argon2_type type : types) {
        // Compute the reference hash via the convenience wrapper
        std::vector<uint8_t> ref_hash(hlen);
        int rc = TypedHashRaw(type, 1, 64, 1,
                               pwd, pwdlen, salt, saltlen,
                               ref_hash.data(), hlen);
        BOOST_REQUIRE_EQUAL(rc, ARGON2_OK);

        // Build a context pointing to a fresh output buffer (verify_ctx will
        // re-compute into ctx.out and compare against the 'hash' argument)
        std::vector<uint8_t> out_buf(hlen);
        std::vector<uint8_t> pwd_buf(pwd, pwd + pwdlen);
        std::vector<uint8_t> salt_buf(salt, salt + saltlen);

        argon2_context ctx;
        std::memset(&ctx, 0, sizeof(ctx));
        ctx.out       = out_buf.data();
        ctx.outlen    = static_cast<uint32_t>(hlen);
        ctx.pwd       = pwd_buf.data();
        ctx.pwdlen    = static_cast<uint32_t>(pwdlen);
        ctx.salt      = salt_buf.data();
        ctx.saltlen   = static_cast<uint32_t>(saltlen);
        ctx.t_cost    = 1;
        ctx.m_cost    = 64;
        ctx.lanes     = 1;
        ctx.threads   = 1;
        ctx.version   = ARGON2_VERSION_NUMBER;
        ctx.flags     = ARGON2_DEFAULT_FLAGS;

        // Correct hash → ARGON2_OK
        switch (type) {
        case Argon2_d:  rc = argon2d_verify_ctx(&ctx,  (const char*)ref_hash.data()); break;
        case Argon2_i:  rc = argon2i_verify_ctx(&ctx,  (const char*)ref_hash.data()); break;
        case Argon2_id: rc = argon2id_verify_ctx(&ctx, (const char*)ref_hash.data()); break;
        default:        rc = ARGON2_INCORRECT_TYPE;
        }
        BOOST_CHECK_MESSAGE(rc == ARGON2_OK,
            "verify_ctx should succeed for type=" << (int)type << " rc=" << rc);

        // Also test generic argon2_verify_ctx
        rc = argon2_verify_ctx(&ctx, (const char*)ref_hash.data(), type);
        BOOST_CHECK_MESSAGE(rc == ARGON2_OK,
            "argon2_verify_ctx (generic) should succeed for type=" << (int)type);

        // Corrupted hash → mismatch
        std::vector<uint8_t> bad_hash = ref_hash;
        bad_hash[0] ^= 0xFF;

        switch (type) {
        case Argon2_d:  rc = argon2d_verify_ctx(&ctx,  (const char*)bad_hash.data()); break;
        case Argon2_i:  rc = argon2i_verify_ctx(&ctx,  (const char*)bad_hash.data()); break;
        case Argon2_id: rc = argon2id_verify_ctx(&ctx, (const char*)bad_hash.data()); break;
        default:        rc = ARGON2_INCORRECT_TYPE;
        }
        BOOST_CHECK_NE(rc, ARGON2_OK);
    }

    Argon2AutoDetect();
}

