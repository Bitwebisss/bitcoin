// ---------------------------------------------------------------------------
// Test 4 – hash_encoded → verify roundtrip (fully in C++, no JSON dependency)
// ---------------------------------------------------------------------------
BOOST_AUTO_TEST_CASE(argon2_verify_roundtrip)
{
    struct Case { argon2_type type; uint32_t t, m, p; size_t hlen; };
    const Case cases[] = {
        {Argon2_d,  1,  64, 1, 32},
        {Argon2_i,  2, 128, 1, 32},
        {Argon2_id, 1,  64, 1, 32},
        {Argon2_d,  1,  64, 1, 16},
        {Argon2_i,  1,  64, 1, 64},
        {Argon2_id, 1,  64, 4, 32},
        {Argon2_d,  3, 256, 1, 32},
        {Argon2_i,  1, 128, 2, 32},
        {Argon2_id, 2,  64, 1, 64},
    };

    const uint8_t pwd[]     = "correct horse battery staple";
    const size_t  pwdlen    = sizeof(pwd) - 1;
    const uint8_t wrong_pwd[] = "Correct Horse Battery Staple";  // capital letters
    const uint8_t salt[]    = "NaCl is a mineral";
    const size_t  saltlen   = sizeof(salt) - 1;

    Argon2AutoDetect(argon2_implementation::STANDARD);

    for (const auto& c : cases) {
        size_t enc_len = argon2_encodedlen(c.t, c.m, c.p,
                                            static_cast<uint32_t>(saltlen),
                                            static_cast<uint32_t>(c.hlen),
                                            c.type);
        std::vector<char> enc_buf(enc_len);
        int rc = TypedHashEncoded(c.type, c.t, c.m, c.p,
                                   pwd, pwdlen, salt, saltlen,
                                   c.hlen, enc_buf.data(), enc_len);
        BOOST_REQUIRE_EQUAL(rc, ARGON2_OK);

        // Correct password → ARGON2_OK
        rc = TypedVerify(c.type, enc_buf.data(), pwd, pwdlen);
        BOOST_CHECK_MESSAGE(rc == ARGON2_OK,
            "verify failed for correct pwd, type=" << (int)c.type);

        // Wrong password → ARGON2_VERIFY_MISMATCH
        rc = TypedVerify(c.type, enc_buf.data(), wrong_pwd, sizeof(wrong_pwd) - 1);
        BOOST_CHECK_MESSAGE(rc == ARGON2_VERIFY_MISMATCH,
            "verify unexpectedly succeeded for wrong pwd, type=" << (int)c.type);

        // Wrong type → should not verify (type is embedded in the string)
        const argon2_type other = (c.type == Argon2_id) ? Argon2_i : Argon2_id;
        rc = TypedVerify(other, enc_buf.data(), pwd, pwdlen);
        BOOST_CHECK_NE(rc, ARGON2_OK);
    }

    Argon2AutoDetect();
}

