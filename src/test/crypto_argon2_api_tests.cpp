// ---------------------------------------------------------------------------
// Test 11 – Invalid parameter handling: expected specific error codes
// ---------------------------------------------------------------------------
BOOST_AUTO_TEST_CASE(argon2_invalid_params)
{
    const uint8_t pwd[]  = "password";
    const size_t  pwdlen = sizeof(pwd) - 1;
    const uint8_t salt[] = "saltsalt";   // 8 bytes (minimum)
    const size_t  saltlen = sizeof(salt) - 1;
    uint8_t out[32] = {};
    char enc[256]   = {};

    // --- _hash_raw bad params ---

    // t_cost = 0
    BOOST_CHECK_EQUAL(
        argon2id_hash_raw(0, 64, 1, pwd, pwdlen, salt, saltlen, out, 32),
        ARGON2_TIME_TOO_SMALL);

    // m_cost = 0
    BOOST_CHECK_EQUAL(
        argon2id_hash_raw(1, 0, 1, pwd, pwdlen, salt, saltlen, out, 32),
        ARGON2_MEMORY_TOO_LITTLE);

    // parallelism = 0
    BOOST_CHECK_EQUAL(
        argon2id_hash_raw(1, 64, 0, pwd, pwdlen, salt, saltlen, out, 32),
        ARGON2_LANES_TOO_FEW);

    // salt < 8 bytes
    BOOST_CHECK_EQUAL(
        argon2id_hash_raw(1, 64, 1, pwd, pwdlen, salt, saltlen - 1, out, 32),
        ARGON2_SALT_TOO_SHORT);

    // hash_len = 0
    BOOST_CHECK_EQUAL(
        argon2id_hash_raw(1, 64, 1, pwd, pwdlen, salt, saltlen, out, 0),
        ARGON2_OUTPUT_TOO_SHORT);

    // Same bad-param checks apply to the other two types
    BOOST_CHECK_EQUAL(
        argon2d_hash_raw(0, 64, 1, pwd, pwdlen, salt, saltlen, out, 32),
        ARGON2_TIME_TOO_SMALL);
    BOOST_CHECK_EQUAL(
        argon2i_hash_raw(0, 64, 1, pwd, pwdlen, salt, saltlen, out, 32),
        ARGON2_TIME_TOO_SMALL);

    // --- _hash_encoded bad params ---

    // Buffer too small → ARGON2_ENCODING_FAIL
    char tiny[4] = "";
    BOOST_CHECK_EQUAL(
        argon2id_hash_encoded(1, 64, 1, pwd, pwdlen, salt, saltlen, 32, tiny, sizeof(tiny)),
        ARGON2_ENCODING_FAIL);

    // --- _verify with garbage encoded string ---
    BOOST_CHECK_NE(argon2id_verify("not-a-valid-argon2-hash", pwd, pwdlen), ARGON2_OK);
    BOOST_CHECK_NE(argon2i_verify("not-a-valid-argon2-hash",  pwd, pwdlen), ARGON2_OK);
    BOOST_CHECK_NE(argon2d_verify("not-a-valid-argon2-hash",  pwd, pwdlen), ARGON2_OK);

    // --- _verify with correct format but wrong type prefix ---
    // Build a valid argon2id encoded string, then ask argon2i_verify to parse it
    size_t enc_len = argon2_encodedlen(1, 64, 1,
                                        static_cast<uint32_t>(saltlen), 32, Argon2_id);
    std::vector<char> enc_buf(enc_len);
    BOOST_REQUIRE_EQUAL(
        argon2id_hash_encoded(1, 64, 1, pwd, pwdlen, salt, saltlen, 32,
                               enc_buf.data(), enc_len),
        ARGON2_OK);
    // argon2i_verify must reject an argon2id-prefixed string
    BOOST_CHECK_NE(argon2i_verify(enc_buf.data(), pwd, pwdlen), ARGON2_OK);
    BOOST_CHECK_NE(argon2d_verify(enc_buf.data(), pwd, pwdlen), ARGON2_OK);

    (void)enc;  // suppress unused-variable warning
}

// ---------------------------------------------------------------------------
// Test 12 – Negative verify: corrupted data or hash must not pass
// ---------------------------------------------------------------------------
BOOST_AUTO_TEST_CASE(argon2_negative_verify)
{
    UniValue root = read_json(json_tests::argon2_api_test_vectors);
    const UniValue& vecs = root["encoded_vectors"];
    BOOST_REQUIRE(vecs.isArray());
    BOOST_REQUIRE_GT(vecs.size(), 0);

    Argon2AutoDetect(argon2_implementation::STANDARD);

    for (const std::string& ts : {"argon2d", "argon2i", "argon2id"}) {
        // Find the first vector matching this type
        for (size_t idx = 0; idx < vecs.size(); ++idx) {
            if (vecs[idx]["type"].get_str() != ts) continue;

            const auto data       = ParseHex(vecs[idx]["data"].get_str());
            const std::string enc = vecs[idx]["encoded"].get_str();
            const argon2_type type = ParseArgon2Type(ts);

            // Correct data → must verify
            BOOST_CHECK_MESSAGE(
                TypedVerify(type, enc.c_str(), data.data(), data.size()) == ARGON2_OK,
                "Expected OK for " << ts);

            // Flipped first byte of data → must not verify
            std::vector<uint8_t> corrupt = data;
            corrupt[0] ^= 0xFF;
            BOOST_CHECK_MESSAGE(
                TypedVerify(type, enc.c_str(), corrupt.data(), corrupt.size()) != ARGON2_OK,
                "Expected mismatch after data corruption for " << ts);

            // Truncated data (different length) → must not verify
            std::vector<uint8_t> truncated(data.begin(), data.begin() + (data.size() / 2));
            if (!truncated.empty()) {
                BOOST_CHECK_NE(
                    TypedVerify(type, enc.c_str(), truncated.data(), truncated.size()),
                    ARGON2_OK);
            }

            break; // one vector per type is sufficient for the negative test
        }
    }

    Argon2AutoDetect();
}

// ---------------------------------------------------------------------------
// Test 13 – ISA consistency: all compiled ISAs must agree for all three types
// ---------------------------------------------------------------------------
BOOST_AUTO_TEST_CASE(argon2_isa_consistency_all_types)
{
    // A handful of well-chosen inputs that cover different byte patterns.
    struct Input { const char* data_hex; const char* salt_hex; };
    const Input inputs[] = {
        {"cafebabe",         "0102030405060708"},
        {"deadbeef",         "fffefdfcfbfaf9f8"},
        {"000102030405060708090a0b0c0d0e0f", "aabbccddeeff00112233445566778899"},
        {"ffffffffffffffff",  "0000000000000000"},
        {"68656c6c6f",        "776f726c64303030"},   // "hello" / "world000"
    };
    constexpr uint32_t t = 1, m = 64, p = 1;
    constexpr size_t   hlen = 32;

    for (const auto& inp : inputs) {
        const auto data = ParseHex(inp.data_hex);
        const auto salt = ParseHex(inp.salt_hex);

        for (argon2_type type : {Argon2_d, Argon2_i, Argon2_id}) {
            // Compute the reference with STANDARD
            Argon2AutoDetect(argon2_implementation::STANDARD);
            std::vector<uint8_t> ref(hlen);
            int rc = TypedHashRaw(type, t, m, p,
                                   data.data(), data.size(),
                                   salt.data(), salt.size(),
                                   ref.data(), hlen);
            BOOST_REQUIRE_EQUAL(rc, ARGON2_OK);

            // Every other compiled ISA must produce the same result
            ForEachISA([&](argon2_implementation::UseImplementation impl,
                           const std::string& isa_name) {
                if (impl == argon2_implementation::STANDARD) return;
                Argon2AutoDetect(impl);
                std::vector<uint8_t> isa_out(hlen);
                rc = TypedHashRaw(type, t, m, p,
                                   data.data(), data.size(),
                                   salt.data(), salt.size(),
                                   isa_out.data(), hlen);
                BOOST_REQUIRE_MESSAGE(rc == ARGON2_OK,
                    isa_name << " failed for type=" << (int)type);
                BOOST_CHECK_MESSAGE(isa_out == ref,
                    isa_name << " differs from STANDARD for type="
                             << (int)type << " data=" << inp.data_hex);
            });
        }
    }

    Argon2AutoDetect();
}

