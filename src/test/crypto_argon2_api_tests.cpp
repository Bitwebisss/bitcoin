// Test 10 – Invalid parameter handling: expected specific error codes
// ---------------------------------------------------------------------------
BOOST_AUTO_TEST_CASE(argon2_invalid_params)
{
    const uint8_t pwd[]  = "password";
    const uint8_t salt[] = "saltsalt";
    const size_t pwdlen  = sizeof(pwd)  - 1;
    const size_t saltlen = sizeof(salt) - 1;
    uint8_t out[32] = {};

    // t_cost = 0
    BOOST_CHECK_EQUAL(
        argon2id_hash_raw(0, 64, 1, pwd, pwdlen, salt, saltlen, out, 32),
        ARGON2_TIME_TOO_SMALL);
    // m_cost = 0
    BOOST_CHECK_EQUAL(
        argon2id_hash_raw(1, 0, 1, pwd, pwdlen, salt, saltlen, out, 32),
        ARGON2_MEMORY_TOO_LITTLE);
    // parallelism = 0
    BOOST_CHECK_EQUAL(
        argon2id_hash_raw(1, 64, 0, pwd, pwdlen, salt, saltlen, out, 32),
        ARGON2_LANES_TOO_FEW);
    // salt too short
    BOOST_CHECK_EQUAL(
        argon2id_hash_raw(1, 64, 1, pwd, pwdlen, salt, saltlen - 1, out, 32),
        ARGON2_SALT_TOO_SHORT);
    // hash_len = 0
    BOOST_CHECK_EQUAL(
        argon2id_hash_raw(1, 64, 1, pwd, pwdlen, salt, saltlen, out, 0),
        ARGON2_OUTPUT_TOO_SHORT);

    // Same checks for the other two types
    BOOST_CHECK_EQUAL(
        argon2d_hash_raw(0, 64, 1, pwd, pwdlen, salt, saltlen, out, 32),
        ARGON2_TIME_TOO_SMALL);
    BOOST_CHECK_EQUAL(
        argon2i_hash_raw(0, 64, 1, pwd, pwdlen, salt, saltlen, out, 32),
        ARGON2_TIME_TOO_SMALL);

    // Encoded buffer too small
    char tiny[4] = "";
    BOOST_CHECK_EQUAL(
        argon2id_hash_encoded(1, 64, 1, pwd, pwdlen, salt, saltlen, 32, tiny, sizeof(tiny)),
        ARGON2_ENCODING_FAIL);

    // Garbage encoded string
    BOOST_CHECK_NE(argon2id_verify("not-a-valid-argon2-hash", pwd, pwdlen), ARGON2_OK);
    BOOST_CHECK_NE(argon2i_verify ("not-a-valid-argon2-hash", pwd, pwdlen), ARGON2_OK);
    BOOST_CHECK_NE(argon2d_verify ("not-a-valid-argon2-hash", pwd, pwdlen), ARGON2_OK);

    // Valid argon2id string rejected by argon2i/argon2d verify
    size_t enc_len = argon2_encodedlen(1, 64, 1,
                                       static_cast<uint32_t>(saltlen), 32, Argon2_id);
    std::vector<char> enc_buf(enc_len);
    BOOST_REQUIRE_EQUAL(
        argon2id_hash_encoded(1, 64, 1, pwd, pwdlen, salt, saltlen, 32,
                              enc_buf.data(), enc_len),
        ARGON2_OK);
    BOOST_CHECK_NE(argon2i_verify(enc_buf.data(), pwd, pwdlen), ARGON2_OK);
    BOOST_CHECK_NE(argon2d_verify(enc_buf.data(), pwd, pwdlen), ARGON2_OK);
}

